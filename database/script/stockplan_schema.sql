CREATE TABLE ROL (
  ID_ROL_PK     NUMBER GENERATED ALWAYS AS IDENTITY,
  NOMBRE_ROL    VARCHAR2(50)  NOT NULL,
  DESCRIPCION   VARCHAR2(100),
  CONSTRAINT ROL_PK        PRIMARY KEY (ID_ROL_PK),
  CONSTRAINT ROL_NOMBRE_UK UNIQUE (NOMBRE_ROL),
  CONSTRAINT ROL_NOMBRE_CK CHECK (NOMBRE_ROL IN ('ADMINISTRADOR','EMPLEADO','USUARIO'))
);

CREATE TABLE USUARIO (
  ID_USUARIO_PK  NUMBER GENERATED ALWAYS AS IDENTITY,
  NOMBRE_US      VARCHAR2(50)  NOT NULL,
  APELLIDO_US    VARCHAR2(50)  NOT NULL,
  EMAIL          VARCHAR2(100) NOT NULL,
  PASSWORD_HASH  VARCHAR2(255) NOT NULL,
  ESTADO         VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  ID_ROL_FK      NUMBER NOT NULL,
  CONSTRAINT USUARIO_PK        PRIMARY KEY (ID_USUARIO_PK),
  CONSTRAINT USUARIO_EMAIL_UK  UNIQUE (EMAIL),
  CONSTRAINT USUARIO_ESTADO_CK CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
  CONSTRAINT USUARIO_ROL_FK    FOREIGN KEY (ID_ROL_FK) REFERENCES ROL (ID_ROL_PK)
);

CREATE TABLE PROVEEDOR (
  ID_PROVEEDOR_PK    NUMBER GENERATED ALWAYS AS IDENTITY,
  NOMBRE_PROVEEDOR   VARCHAR2(100) NOT NULL,
  APELLIDO_PROVEEDOR VARCHAR2(50),
  TELEFONO_PROVEEDOR VARCHAR2(30),
  DIAS_ENTREGA       NUMBER(3) DEFAULT 7 NOT NULL,
  ESTADO             VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT PROVEEDOR_PK        PRIMARY KEY (ID_PROVEEDOR_PK),
  CONSTRAINT PROVEEDOR_ESTADO_CK CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
  CONSTRAINT PROVEEDOR_DIAS_CK   CHECK (DIAS_ENTREGA >= 0)
);

CREATE TABLE PRODUCTOS (
  ID_PRODUCTO_PK       NUMBER GENERATED ALWAYS AS IDENTITY,
  NOMBRE_PRODUCTO      VARCHAR2(100) NOT NULL,
  DESCRIPCION_PRODUCTO VARCHAR2(500),
  PRECIO               NUMBER(12,2) NOT NULL,
  ID_PROVEEDOR_FK      NUMBER NOT NULL,
  ESTADO               VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT PRODUCTOS_PK           PRIMARY KEY (ID_PRODUCTO_PK),
  CONSTRAINT PRODUCTOS_PRECIO_CK    CHECK (PRECIO >= 0),
  CONSTRAINT PRODUCTOS_ESTADO_CK    CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
  CONSTRAINT PRODUCTOS_PROVEEDOR_FK FOREIGN KEY (ID_PROVEEDOR_FK) REFERENCES PROVEEDOR (ID_PROVEEDOR_PK)
);

CREATE TABLE TALLA (
  ID_TALLA_PK  NUMBER GENERATED ALWAYS AS IDENTITY,
  NOMBRE_TALLA VARCHAR2(20) NOT NULL,
  CONSTRAINT TALLA_PK        PRIMARY KEY (ID_TALLA_PK),
  CONSTRAINT TALLA_NOMBRE_UK UNIQUE (NOMBRE_TALLA)
);

CREATE TABLE REFERENCIA_PRODUCTO (
  ID_REFERENCIA_PK NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_PRODUCTO_FK   NUMBER NOT NULL,
  ID_TALLA_FK      NUMBER NOT NULL,
  ESTADO           VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT REFERENCIA_PK          PRIMARY KEY (ID_REFERENCIA_PK),
  CONSTRAINT REFERENCIA_UK          UNIQUE (ID_PRODUCTO_FK, ID_TALLA_FK),
  CONSTRAINT REFERENCIA_ESTADO_CK   CHECK (ESTADO IN ('ACTIVO','INACTIVO')),
  CONSTRAINT REFERENCIA_PRODUCTO_FK FOREIGN KEY (ID_PRODUCTO_FK) REFERENCES PRODUCTOS (ID_PRODUCTO_PK),
  CONSTRAINT REFERENCIA_TALLA_FK    FOREIGN KEY (ID_TALLA_FK) REFERENCES TALLA (ID_TALLA_PK)
);

CREATE TABLE INVENTARIO (
  ID_INVENTARIO_PK    NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_REFERENCIA_FK    NUMBER NOT NULL,
  CANTIDAD_ACTUAL     NUMBER(10) DEFAULT 0 NOT NULL,
  CANTIDAD_RESERVADA  NUMBER(10) DEFAULT 0 NOT NULL,
  STOCK_MINIMO        NUMBER(10) DEFAULT 0 NOT NULL,
  FECHA_ACTUALIZACION DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT INVENTARIO_PK            PRIMARY KEY (ID_INVENTARIO_PK),
  CONSTRAINT INVENTARIO_REFERENCIA_UK UNIQUE (ID_REFERENCIA_FK),
  CONSTRAINT INVENTARIO_REFERENCIA_FK FOREIGN KEY (ID_REFERENCIA_FK) REFERENCES REFERENCIA_PRODUCTO (ID_REFERENCIA_PK),
  CONSTRAINT INVENTARIO_ACTUAL_CK     CHECK (CANTIDAD_ACTUAL >= 0),
  CONSTRAINT INVENTARIO_RESERV_CK     CHECK (CANTIDAD_RESERVADA >= 0 AND CANTIDAD_RESERVADA <= CANTIDAD_ACTUAL)
);

CREATE TABLE RECEPCION (
  ID_RECEPCION_PK    NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_PROVEEDOR_FK    NUMBER NOT NULL,
  ID_REFERENCIA_FK   NUMBER NOT NULL,
  ID_USUARIO_FK      NUMBER NOT NULL,
  FECHA_INGRESO      DATE DEFAULT SYSDATE NOT NULL,
  CANTIDAD_ESPERADA  NUMBER(10) NOT NULL,
  CANTIDAD_RECIBIDA  NUMBER(10) NOT NULL,
  CANTIDAD_ACEPTADA  NUMBER(10) NOT NULL,
  CANTIDAD_RECHAZADA NUMBER(10) NOT NULL,
  MOTIVO_RECHAZO     VARCHAR2(200),
  ESTADO             VARCHAR2(20) DEFAULT 'REGISTRADA' NOT NULL,
  OBSERVACION        VARCHAR2(500),
  CONSTRAINT RECEPCION_PK            PRIMARY KEY (ID_RECEPCION_PK),
  CONSTRAINT RECEPCION_ESTADO_CK     CHECK (ESTADO IN ('REGISTRADA','CONFIRMADA','ANULADA')),
  CONSTRAINT RECEPCION_CANT_CK       CHECK (CANTIDAD_ESPERADA >= 0 AND CANTIDAD_RECIBIDA >= 0 AND CANTIDAD_ACEPTADA >= 0 AND CANTIDAD_RECHAZADA >= 0),
  CONSTRAINT RECEPCION_SUMA_CK       CHECK (CANTIDAD_RECIBIDA = CANTIDAD_ACEPTADA + CANTIDAD_RECHAZADA),
  CONSTRAINT RECEPCION_PROVEEDOR_FK  FOREIGN KEY (ID_PROVEEDOR_FK) REFERENCES PROVEEDOR (ID_PROVEEDOR_PK),
  CONSTRAINT RECEPCION_REFERENCIA_FK FOREIGN KEY (ID_REFERENCIA_FK) REFERENCES REFERENCIA_PRODUCTO (ID_REFERENCIA_PK),
  CONSTRAINT RECEPCION_USUARIO_FK    FOREIGN KEY (ID_USUARIO_FK) REFERENCES USUARIO (ID_USUARIO_PK)
);

CREATE TABLE PEDIDO (
  ID_PEDIDO_PK   NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_USUARIO_FK  NUMBER NOT NULL,
  FECHA_PEDIDO   DATE DEFAULT SYSDATE NOT NULL,
  FECHA_ENTREGA  DATE,
  ESTADO         VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
  CONSTRAINT PEDIDO_PK         PRIMARY KEY (ID_PEDIDO_PK),
  CONSTRAINT PEDIDO_ESTADO_CK  CHECK (ESTADO IN ('PENDIENTE','INCOMPLETO','COMPLETO','RECLAMADO','CANCELADO')),
  CONSTRAINT PEDIDO_USUARIO_FK FOREIGN KEY (ID_USUARIO_FK) REFERENCES USUARIO (ID_USUARIO_PK)
);

CREATE TABLE DETALLE_PEDIDO (
  ID_DETALLE_PEDIDO_PK NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_PEDIDO_FK         NUMBER NOT NULL,
  ID_REFERENCIA_FK     NUMBER NOT NULL,
  CANTIDAD_PEDIDO      NUMBER(10) NOT NULL,
  CANTIDAD_DISPONIBLE  NUMBER(10) DEFAULT 0 NOT NULL,
  PRECIO_UNITARIO      NUMBER(12,2) NOT NULL,
  CONSTRAINT DETALLE_PEDIDO_PK        PRIMARY KEY (ID_DETALLE_PEDIDO_PK),
  CONSTRAINT DETALLE_PEDIDO_UK        UNIQUE (ID_PEDIDO_FK, ID_REFERENCIA_FK),
  CONSTRAINT DETALLE_PEDIDO_CANT_CK   CHECK (CANTIDAD_PEDIDO > 0 AND CANTIDAD_DISPONIBLE >= 0 AND CANTIDAD_DISPONIBLE <= CANTIDAD_PEDIDO),
  CONSTRAINT DETALLE_PEDIDO_PRECIO_CK CHECK (PRECIO_UNITARIO >= 0),
  CONSTRAINT DETALLE_PEDIDO_PEDIDO_FK FOREIGN KEY (ID_PEDIDO_FK) REFERENCES PEDIDO (ID_PEDIDO_PK),
  CONSTRAINT DETALLE_PEDIDO_REFERENCIA_FK FOREIGN KEY (ID_REFERENCIA_FK) REFERENCES REFERENCIA_PRODUCTO (ID_REFERENCIA_PK)
);

CREATE TABLE PROCESO_PEDIDO (
  ID_PROCESO_PEDIDO_PK NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_PEDIDO_FK         NUMBER NOT NULL,
  ID_USUARIO_FK        NUMBER NOT NULL,
  ESTADO               VARCHAR2(20) NOT NULL,
  FECHA                DATE DEFAULT SYSDATE NOT NULL,
  OBSERVACION          VARCHAR2(500),
  CONSTRAINT PROCESO_PEDIDO_PK        PRIMARY KEY (ID_PROCESO_PEDIDO_PK),
  CONSTRAINT PROCESO_PEDIDO_ESTADO_CK CHECK (ESTADO IN ('PENDIENTE','INCOMPLETO','COMPLETO','RECLAMADO','CANCELADO')),
  CONSTRAINT PROCESO_PEDIDO_PEDIDO_FK FOREIGN KEY (ID_PEDIDO_FK) REFERENCES PEDIDO (ID_PEDIDO_PK),
  CONSTRAINT PROCESO_PEDIDO_USUARIO_FK FOREIGN KEY (ID_USUARIO_FK) REFERENCES USUARIO (ID_USUARIO_PK)
);

CREATE TABLE MOVIMIENTO_INVENTARIO (
  ID_MOVIMIENTO_PK     NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_REFERENCIA_FK     NUMBER NOT NULL,
  TIPO                 VARCHAR2(30) NOT NULL,
  CANTIDAD             NUMBER(10) NOT NULL,
  FECHA                DATE DEFAULT SYSDATE NOT NULL,
  ID_USUARIO_FK        NUMBER NOT NULL,
  ID_RECEPCION_FK      NUMBER,
  ID_DETALLE_PEDIDO_FK NUMBER,
  OBSERVACION          VARCHAR2(500),
  CONSTRAINT MOVIMIENTO_PK            PRIMARY KEY (ID_MOVIMIENTO_PK),
  CONSTRAINT MOVIMIENTO_TIPO_CK       CHECK (TIPO IN ('ENTRADA_RECEPCION','SALIDA_PEDIDO','AJUSTE')),
  CONSTRAINT MOVIMIENTO_CANT_CK       CHECK (CANTIDAD <> 0),
  CONSTRAINT MOVIMIENTO_REFERENCIA_FK FOREIGN KEY (ID_REFERENCIA_FK) REFERENCES REFERENCIA_PRODUCTO (ID_REFERENCIA_PK),
  CONSTRAINT MOVIMIENTO_USUARIO_FK    FOREIGN KEY (ID_USUARIO_FK) REFERENCES USUARIO (ID_USUARIO_PK),
  CONSTRAINT MOVIMIENTO_RECEPCION_FK  FOREIGN KEY (ID_RECEPCION_FK) REFERENCES RECEPCION (ID_RECEPCION_PK),
  CONSTRAINT MOVIMIENTO_DET_PEDIDO_FK FOREIGN KEY (ID_DETALLE_PEDIDO_FK) REFERENCES DETALLE_PEDIDO (ID_DETALLE_PEDIDO_PK)
);
